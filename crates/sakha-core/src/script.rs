//! The session script: the R2 code of everything done in Sakha, in order,
//! each step under a comment — the reproducible record of a menu-driven
//! analysis. A step is recorded once (opening `score` twice adds it once).

#[derive(Debug, Clone, Default)]
pub struct SessionScript {
    header: Vec<String>,
    steps: Vec<(String, String, String)>,
}

impl SessionScript {
    /// A new script for data frame `df`; `load` is the line that loaded it
    /// (`None` when it was already in the session).
    pub fn new(df: &str, date: &str, load: Option<&str>) -> SessionScript {
        let mut header = vec![format!("# Sakha session - {df} - {date}"),
                              "# Generated by R2Sakha. Run it all in the Studio: Ctrl+Shift+Enter.".into()];
        match load {
            Some(l) => header.push(l.to_string()),
            None => header.push(format!("# '{df}' was made in the console; add the line that loads it here")),
        }
        SessionScript { header, steps: vec![] }
    }

    /// Add a step under `key` unless that key is already recorded. Each
    /// line of `code` becomes a line of the script.
    pub fn record(&mut self, key: &str, comment: &str, code: &[String]) -> bool {
        if self.steps.iter().any(|(k, _, _)| k == key) { return false; }
        self.steps.push((key.to_string(), comment.to_string(), code.join("\n")));
        true
    }

    pub fn steps(&self) -> usize { self.steps.len() }

    /// The parts a `.sakha` file stores: the header, then (key, comment, code).
    pub fn parts(&self) -> (&[String], &[(String, String, String)]) { (&self.header, &self.steps) }

    pub fn from_parts(header: Vec<String>, steps: Vec<(String, String, String)>) -> SessionScript {
        SessionScript { header, steps }
    }

    /// The steps that changed the data, to run again on reopening.
    pub fn data_steps(&self) -> Vec<String> {
        self.steps.iter().filter(|(k, _, _)| k.starts_with("cat:")).map(|(_, _, code)| code.clone()).collect()
    }

    pub fn text(&self) -> String {
        let mut out = self.header.join("\n");
        for (_, comment, code) in &self.steps {
            out.push_str(&format!("\n\n# {comment}\n{code}"));
        }
        out.push('\n');
        out
    }
}

/// The default script file name for a data frame.
pub fn default_script_name(df: &str) -> String { format!("{df}_sakha") }

/// The console command that loaded `df` from a file, if the history has
/// one: the latest `df <- read...(...)`. It starts a session script, so the
/// exported script runs on its own.
pub fn load_line_from_history(df: &str, history: &[String]) -> Option<String> {
    history.iter().rev().find(|line| {
        let Some(rest) = line.trim().strip_prefix(df) else { return false };
        let rest = rest.trim_start();
        let rhs = if let Some(r) = rest.strip_prefix("<-") { r }
                  else if let Some(r) = rest.strip_prefix('=').filter(|r| !r.starts_with('=')) { r }
                  else { return false };
        rhs.trim_start().starts_with("read")
    }).map(|l| l.trim().to_string())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn records_each_step_once_in_order() {
        let mut s = SessionScript::new("trial", "2026-11-05", Some("trial <- read.csv(\"t.csv\")"));
        assert!(s.record("col:score", "score: summary", &["summary(trial$score)".into(), "hist(trial$score)".into()]));
        assert!(!s.record("col:score", "again", &["x".into()]), "a step is recorded once");
        assert!(s.record("cat:dose", "dose as a category", &["trial$dose <- factor(trial$dose)".into()]));
        let t = s.text();
        assert!(t.starts_with("# Sakha session - trial - 2026-11-05\n"));
        assert!(t.contains("trial <- read.csv(\"t.csv\")\n\n# score: summary\nsummary(trial$score)\nhist(trial$score)"));
        assert!(t.ends_with("# dose as a category\ntrial$dose <- factor(trial$dose)\n"));
        assert_eq!(s.steps(), 2);
        assert!(SessionScript::new("d", "x", None).text().contains("'d' was made in the console"));
    }

    #[test]
    fn the_load_line_comes_from_the_history() {
        let h: Vec<String> = ["x <- 1", "trial <- read.csv(\"a.csv\")", "trial2 <- read.csv(\"b.csv\")",
                              "trial == 3", "trial = read.csv(\"c.csv\")", "mean(trial$score)"]
            .iter().map(|s| s.to_string()).collect();
        assert_eq!(load_line_from_history("trial", &h).as_deref(), Some("trial = read.csv(\"c.csv\")"));
        assert_eq!(load_line_from_history("x", &h), None);
    }
}
